#!/usr/bin/env bash
# em-pr-check.sh — record a PR-ready task and arm the watcher's merge poll.
#
# Usage:
#   em-pr-check.sh <id> <pr-url>
#
# Writes pr=<url> into the task's meta and generates state/<id>.check.sh,
# which the watcher runs every EM_CHECK_INTERVAL: it prints one line when
# the PR is merged or closed (waking the EM), nothing otherwise. Degrades
# silently when gh is unavailable — the heartbeat review is the backstop.
set -euo pipefail
# shellcheck source=bin/lib/common.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/lib/common.sh"
"$EM_BIN/em-guard.sh"

main() {
  local id="${1:-}" url="${2:-}"
  case "$id" in -h | --help) usage; exit 0 ;; esac
  [ -n "$id" ] && [ -n "$url" ] || { usage >&2; exit 1; }
  require_id "$id"
  case "$url" in
    https://*/pull/* | https://*/pulls/*) ;;
    *) die "'$url' does not look like a PR URL (want https://…/pull/<n>)" ;;
  esac

  meta_set "$id" pr "$url" || die "no meta record for task $id"
  emit_event "$id" pr_opened --actor em \
    --data "$(jq -cn --arg url "$url" '{url: $url}' 2>/dev/null || true)"

  # The merged event fires from the generated poll (marker-guarded: the poll
  # re-fires every interval until teardown, the event must land once).
  local check="$EM_STATE/$id.check.sh" merged_data
  merged_data="$(jq -cn --arg url "$url" '{url: $url}' 2>/dev/null || printf '{}')"
  cat > "$check" <<EOF
#!/usr/bin/env bash
# auto-generated by em-pr-check.sh — merge poll for $id
state="\$(gh pr view '$url' --json state --jq .state 2>/dev/null)" || exit 0
case "\$state" in
  MERGED)
    if [ ! -f '$EM_STATE/$id.merged-event' ]; then
      '$EM_BIN/em-log-event.sh' '$id' merged --actor watcher --data '$merged_data' >/dev/null 2>&1 || true
      touch '$EM_STATE/$id.merged-event' 2>/dev/null || true
    fi
    echo "PR merged: $url"
    ;;
  CLOSED) echo "PR closed without merging: $url" ;;
esac
EOF
  chmod +x "$check"
  log "merge poll armed for $id ($url)"
}

main "$@"
